// Danh sách các khóa từ vựng sắp xếp từ dài nhất đến ngắn nhất để ưu tiên match từ ghép dài trước
const SORTED_KANJI_KEYS = Object.keys(KANJI_FURIGANA_DICT).sort((a, b) => b.length - a.length);

/**
 * Phân tích 1 từ vựng (word + reading) để gắn Furigana chuẩn xác từng phần
 * Ví dụ:
 * - 静かな + しずかな => [{ text: "静", furigana: "しず" }, { text: "かな" }]
 * - 領収書 + りょうしゅうしょ => [{ text: "領収書", furigana: "りょうしゅうしょ" }]
 * - 降ろす + おろす => [{ text: "降", furigana: "お" }, { text: "ろす" }]
 * - エレベーター + えれべえたあ => [{ text: "エレベーター" }] (không có chữ Hán)
 */
export function parseWordFurigana(word: string, reading?: string): FuriganaSegment[] {
  if (!word) return [];

  // Nếu không có chữ Hán nào trong từ, trả về nguyên bản
  if (!/[\u4e00-\u9faf]/.test(word)) {
    return [{ text: word }];
  }

  const rawReading = reading || KANJI_FURIGANA_DICT[word] || "";
  if (!rawReading) {
    // Thử tìm trong từ điển
    if (KANJI_FURIGANA_DICT[word]) {
      return [{ text: word, furigana: KANJI_FURIGANA_DICT[word] }];
    }
    return [{ text: word }];
  }

  // 1. Nếu từ hoàn toàn là chữ Hán (không có hiragana/katakana kẹp kèm)
  if (/^[\u4e00-\u9faf]+$/.test(word)) {
    return [{ text: word, furigana: rawReading }];
  }

  // 2. Tách phần đuôi Okurigana (trailing kana)
  let suffixLen = 0;
  while (
    suffixLen < word.length &&
    suffixLen < rawReading.length &&
    word[word.length - 1 - suffixLen] === rawReading[rawReading.length - 1 - suffixLen] &&
    !/[\u4e00-\u9faf]/.test(word[word.length - 1 - suffixLen])
  ) {
    suffixLen++;
  }

  // 3. Tách phần đầu Okurigana (leading kana, ví dụ お茶 -> お + 茶)
  let prefixLen = 0;
  while (
    prefixLen < word.length - suffixLen &&
    prefixLen < rawReading.length - suffixLen &&
    word[prefixLen] === rawReading[prefixLen] &&
    !/[\u4e00-\u9faf]/.test(word[prefixLen])
  ) {
    prefixLen++;
  }

  const prefix = word.slice(0, prefixLen);
  const suffix = suffixLen > 0 ? word.slice(word.length - suffixLen) : "";
  const kanjiPart = word.slice(prefixLen, word.length - suffixLen);
  const kanjiReading = rawReading.slice(prefixLen, rawReading.length - suffixLen);

  const segments: FuriganaSegment[] = [];
  if (prefix) segments.push({ text: prefix });
  if (kanjiPart) {
    segments.push({ text: kanjiPart, furigana: kanjiReading });
  }
  if (suffix) segments.push({ text: suffix });

  return segments;
}

/**
 * Tự động phân tích toàn bộ câu tiếng Nhật (Ví dụ câu trong bài học / câu ví dụ)
 * Quét nhận diện tất cả các cụm chữ Hán và tự động gắn Furigana chính xác
 */
export function parseSentenceFurigana(sentence: string): FuriganaSegment[] {
  if (!sentence) return [];

  // Nếu câu không có chữ Hán nào, trả về trực tiếp
  if (!/[\u4e00-\u9faf]/.test(sentence)) {
    return [{ text: sentence }];
  }

  const segments: FuriganaSegment[] = [];
  let index = 0;
  let nonKanjiAccum = "";

  while (index < sentence.length) {
    // Kiểm tra xem tại vị trí này có khớp với từ ghép / chữ Hán nào trong từ điển không
    let matchedKey: string | null = null;
    for (const key of SORTED_KANJI_KEYS) {
      if (sentence.startsWith(key, index)) {
        matchedKey = key;
        break;
      }
    }

    if (matchedKey) {
      if (nonKanjiAccum) {
        segments.push({ text: nonKanjiAccum });
        nonKanjiAccum = "";
      }
      segments.push({
        text: matchedKey,
        furigana: KANJI_FURIGANA_DICT[matchedKey],
      });
      index += matchedKey.length;
      continue;
    }

    // Nếu là chữ Hán đơn lẻ chưa có trong từ điển
    const char = sentence[index];
    if (/[\u4e00-\u9faf]/.test(char)) {
      if (nonKanjiAccum) {
        segments.push({ text: nonKanjiAccum });
        nonKanjiAccum = "";
      }
      // Xem ký tự đơn lẻ có trong từ điển không
      const singleReading = KANJI_FURIGANA_DICT[char];
      segments.push({
        text: char,
        furigana: singleReading,
      });
      index++;
      continue;
    }

    // Ký tự thông thường (Hiragana, Katakana, số, dấu câu)
    nonKanjiAccum += char;
    index++;
  }

  if (nonKanjiAccum) {
    segments.push({ text: nonKanjiAccum });
  }

  return segments;
}
