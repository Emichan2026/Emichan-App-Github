export function getLocalizedText(text: string | undefined | null, lang: string | undefined | null): string {
  if (!text) return "";
  
  // Look for slash separation, which can be formatted as " / " or "\n/" or "\n /" or "/\n"
  const splitters = ["\n/ ", "\n/", " / \n", " / ", " /", "/ "];
  for (const sep of splitters) {
    if (text.includes(sep)) {
      const parts = text.split(sep);
      if (parts.length >= 2) {
        return lang === "vi" ? parts[0].trim() : parts[1].trim();
      }
    }
  }
  
  // Simple "/" separation with some guards
  if (text.includes("/")) {
    if (!text.includes("://") && !/^[a-zA-Z0-9_-]+\/[a-zA-Z0-9_-]+$/.test(text)) {
      const parts = text.split("/");
      if (parts.length >= 2) {
        return lang === "vi" ? parts[0].trim() : parts[1].trim();
      }
    }
  }
  
  return text;
}
