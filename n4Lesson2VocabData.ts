/**
 * Chuyển đổi chính xác từ vựng Buổi 2 sang âm đọc chuẩn cho voice đọc:
 * 1. Đọc đủ chữ, đủ âm tất cả các chữ cái và mora.
 * 2. Đọc đúng chữ Hán theo Hiragana đã ghi trong file PDF Buổi 2.
 * 3. Kéo dài trường âm Katakana.
 */
export function toTTSPhoneticReadingLesson2(itemOrText: N4VocabItem | string): string {
  let text = '';

  if (typeof itemOrText === 'object' && itemOrText !== null) {
    text = itemOrText.reading || itemOrText.word;
  } else {
    text = String(itemOrText || '').trim();
    // Bỏ phần （する）nếu có để tra cứu chính xác
    const cleanWord = text.replace(/（する）|\(する\)/g, '').trim();
    if (KANJI_READING_OVERRIDE_MAP_L2[cleanWord]) {
      text = KANJI_READING_OVERRIDE_MAP_L2[cleanWord];
    } else if (KANJI_READING_OVERRIDE_MAP_L2[text]) {
      text = KANJI_READING_OVERRIDE_MAP_L2[text];
    } else {
      const kanjiKeys = Object.keys(KANJI_READING_OVERRIDE_MAP_L2).sort((a, b) => b.length - a.length);
      for (const k of kanjiKeys) {
        if (text.includes(k)) {
          text = text.split(k).join(KANJI_READING_OVERRIDE_MAP_L2[k]);
        }
      }
    }
  }

  // Đổi dấu chấm giữa "・" thành dấu phẩy ngắt nghỉ tự nhiên
  text = text.replace(/・/g, '、');
  text = text.replace(/（する）|\(する\)/g, '').trim();

  let hira = '';
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (ch === 'ー') {
      const prev = hira[hira.length - 1] || '';
      const vowel = getVowelOfChar(prev);
      hira += vowel;
    } else if (KATAKANA_TO_HIRAGANA_MAP[ch]) {
      hira += KATAKANA_TO_HIRAGANA_MAP[ch];
    } else {
      hira += ch;
    }
  }
  return hira.trim();
}

